def resolve_lang(code: str | None, fallback: str = FALLBACK) -> str:
    if code and code in UI_LANGS and code != "auto":
        return code
    if not code:
        return fallback if fallback in UI_LANGS else FALLBACK
    base = code.lower().replace("_", "-").split("-")[0]
    if base in UI_LANGS:
        return base
    return fallback if fallback in UI_LANGS else FALLBACK


def t(key: str, lang: str | None = None, **kwargs: Any) -> str:
    lang = resolve_lang(lang)
    table = STRINGS.get(lang) or STRINGS[FALLBACK]
    template = table.get(key) or STRINGS[FALLBACK].get(key) or key
    if kwargs:
        return template.format(**kwargs)
    return template


def format_duration(seconds: int, lang: str | None = None) -> str:
    lang = resolve_lang(lang)
    if seconds < 60:
        return t("dur.seconds", lang, n=seconds)
    if seconds < 3600:
        return t("dur.minutes", lang, n=seconds // 60)
    if seconds < 86400:
        hours = seconds // 3600
        minutes = (seconds % 3600) // 60
        if minutes:
            return t("dur.hours_min", lang, h=hours, m=minutes)
        return t("dur.hours", lang, n=hours)
    days = seconds // 86400
    hours = (seconds % 86400) // 3600
    if hours:
        return t("dur.days_hours", lang, d=days, h=hours)
    return t("dur.days", lang, n=days)


def media_label(kind: str, lang: str | None = None) -> str:
    return t(f"media.{kind}", lang)


def assert_complete() -> None:
    keys = set(STRINGS[FALLBACK])
    formatter = Formatter()
    reserved = {"key", "lang"}
    for lang, table in STRINGS.items():
        missing = keys - set(table)
        extra = set(table) - keys
        if missing or extra:
            raise AssertionError(f"{lang} missing={sorted(missing)} extra={sorted(extra)}")
        for key, template in table.items():
            fields = {
                field_name
                for _, field_name, _, _ in formatter.parse(template)
                if field_name
            }
            fallback_fields = {
                field_name
                for _, field_name, _, _ in formatter.parse(STRINGS[FALLBACK][key])
                if field_name
            }
            if fields != fallback_fields:
                raise AssertionError(
                    f"{lang}.{key} placeholders={sorted(fields)} "
                    f"expected={sorted(fallback_fields)}"
                )
            if fields & reserved:
                raise AssertionError(
                    f"{lang}.{key} uses reserved placeholders={sorted(fields & reserved)}"
                )
